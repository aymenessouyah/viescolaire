-- =========================================================================
--  Espace pédagogique STI — base de sauvegarde (Supabase / PostgreSQL)
--  Multi-professeurs : chaque compte connecté possède SES sauvegardes.
--
--  À exécuter UNE SEULE FOIS : Supabase → SQL Editor → New query →
--  coller tout ce texte → Run. Aucune modification nécessaire.
--
--  Les comptes des professeurs sont créés par l'administrateur du projet :
--  Authentication → Users → Add user → Create new user
--  (adresse + mot de passe, cocher « Auto Confirm User »).
--  Les inscriptions restent fermées : Authentication → Sign In / Providers →
--  « Allow new users to sign up » : OFF.
-- =========================================================================

-- 1) Table des sauvegardes (instantanés de l'espace pédagogique) ------------
create table if not exists public.espace_pedagogique (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  prof         text,                 -- nom du professeur (affiché)
  lycee        text,
  annee        text,
  device       text,                 -- « Téléphone », « Poste du lycée »…
  prof_id      uuid default auth.uid(),   -- propriétaire (compte connecté)
  payload      jsonb not null        -- { times, seances, profil, classes,
                                    --   eleves, epreuves, notes, presences }
);

create index if not exists espace_pedagogique_created_at_idx
  on public.espace_pedagogique (created_at desc);

-- 2) Sécurité : chaque professeur ne voit que SES sauvegardes --------------
alter table public.espace_pedagogique enable row level security;

drop policy if exists "lecture authentifiee"          on public.espace_pedagogique;
drop policy if exists "ecriture authentifiee"         on public.espace_pedagogique;
drop policy if exists "lecture proprietaire"          on public.espace_pedagogique;
drop policy if exists "ecriture proprietaire"         on public.espace_pedagogique;
drop policy if exists "lecture espace"                on public.espace_pedagogique;
drop policy if exists "ecriture espace"               on public.espace_pedagogique;
drop policy if exists "lecture espace (propre prof)"  on public.espace_pedagogique;
drop policy if exists "ecriture espace (propre prof)" on public.espace_pedagogique;

create policy "lecture espace (propre prof)"
  on public.espace_pedagogique for select
  to authenticated
  using (prof_id = auth.uid());

create policy "ecriture espace (propre prof)"
  on public.espace_pedagogique for insert
  to authenticated
  with check (prof_id = auth.uid());

-- Droits minimaux nécessaires à la fonction (RLS reste la barrière de données).
revoke all on public.espace_pedagogique from public, anon;
grant select, insert on public.espace_pedagogique to authenticated;
do $$
declare
  v_id_sequence text := pg_catalog.pg_get_serial_sequence('public.espace_pedagogique', 'id');
begin
  if v_id_sequence is not null then
    execute format('revoke all on sequence %s from public, anon', v_id_sequence);
    execute format('grant usage, select on sequence %s to authenticated', v_id_sequence);
  end if;
end;
$$;

-- Sans connexion, la table est totalement inaccessible.

-- 3) Synchronisation atomique multi-appareils ------------------------------
-- L'application appelle cette fonction pour échanger les instantanés.
-- Le verrou et le contrôle p_expected_id évitent qu'un appareil écrase les
-- modifications publiées par un autre depuis son dernier échange.
create or replace function public.sti_sync_snapshot(
  p_annee text,
  p_expected_id text default null,
  p_snapshot jsonb default null,
  p_commit boolean default false
) returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_head public.espace_pedagogique%rowtype;
  v_id bigint;
  v_exists boolean;
begin
  if v_uid is null then raise exception 'Connexion obligatoire' using errcode = '28000'; end if;
  if p_annee is null or length(p_annee) not between 4 and 40 then
    raise exception 'Annee invalide' using errcode = '22023';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(v_uid::text || '|' || p_annee, 0)
  );

  select * into v_head from public.espace_pedagogique
    where prof_id = v_uid and annee = p_annee order by id desc limit 1;
  v_exists := found;

  if not p_commit then
    return jsonb_build_object('status','read','head',case when v_exists then
      jsonb_build_object('id',v_head.id::text,'payload',v_head.payload,'created_at',v_head.created_at)
      else null end);
  end if;

  if (case when v_exists then v_head.id::text else null end) is distinct from p_expected_id then
    return jsonb_build_object('status','retry','head',case when v_exists then
      jsonb_build_object('id',v_head.id::text,'payload',v_head.payload,'created_at',v_head.created_at)
      else null end);
  end if;

  if p_snapshot is null or jsonb_typeof(p_snapshot) <> 'object'
     or jsonb_typeof(p_snapshot->'payload') is distinct from 'object' then
    raise exception 'Instantane invalide' using errcode = '22023';
  end if;

  insert into public.espace_pedagogique(prof,lycee,annee,device,prof_id,payload)
    values(p_snapshot->>'prof',p_snapshot->>'lycee',p_annee,p_snapshot->>'device',v_uid,p_snapshot->'payload')
    returning id into v_id;
  select * into v_head from public.espace_pedagogique where id=v_id and prof_id=v_uid;
  return jsonb_build_object('status','committed','head',jsonb_build_object(
    'id',v_head.id::text,'payload',v_head.payload,'created_at',v_head.created_at));
end;
$$;

revoke all on function public.sti_sync_snapshot(text,text,jsonb,boolean) from public;
revoke all on function public.sti_sync_snapshot(text,text,jsonb,boolean) from anon;
grant execute on function public.sti_sync_snapshot(text,text,jsonb,boolean) to authenticated;

